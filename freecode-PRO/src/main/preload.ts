import { contextBridge, ipcRenderer } from 'electron';

const invoke = (channel: string, ...args: unknown[]) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('api', {
  getSettings: () => invoke('settings:get'),
  setSettings: (patch: Record<string, unknown>) => invoke('settings:set', patch),
  pickWorkspace: () => invoke('workspace:pick'),
  setWorkspace: (dir: string) => invoke('workspace:set', dir),
  listTree: (rel: string) => invoke('tree:list', rel),
  readFile: (rel: string) => invoke('file:read', rel),
  searchFiles: (q: string) => invoke('files:search', q),
  listModels: () => invoke('models:list'),
  openExternal: (url: string) => invoke('open:external', url),
  listSessions: () => invoke('sessions:list'),
  newSession: () => invoke('sessions:new'),
  loadSession: (id: string) => invoke('sessions:load', id),
  deleteSession: (id: string) => invoke('sessions:delete', id),
  send: (text: string, images?: string[]) => invoke('chat:send', text, images),
  abort: () => invoke('chat:abort'),
  undo: () => invoke('chat:undo'),
  compact: () => invoke('chat:compact'),
  listCommands: () => invoke('commands:list'),
  mcpStatus: () => invoke('mcp:status'),
  mcpReload: () => invoke('mcp:reload'),
  respondApproval: (id: string, ok: boolean, scope?: 'once' | 'turn' | 'file') => invoke('approval:respond', id, ok, scope),
  telemetrySummary: () => invoke('telemetry:summary'),
  telemetryFailures: (opts?: { asTask?: boolean }) => invoke('telemetry:failures', opts),
  telemetryClear: () => invoke('telemetry:clear'),
  metricsDashboard: (opts?: { limit?: number }) => invoke('metrics:dashboard', opts),
  metricsExport: () => invoke('metrics:export'),
  metricsSweepNow: () => invoke('metrics:sweep-now'),
  scheduleStatus: () => invoke('schedule:status'),
  scheduleSet: (patch: { enabled?: boolean; everyHours?: number }) => invoke('schedule:set', patch),
  bridgeCommand: (action: string, arg = '') => invoke('bridge:command', action, arg),
  bridgeSettings: (patch: { url?: string; mode?: 'ask' | 'readonly'; hosts?: string[] }) => invoke('bridge:settings', patch),
  bridgeHostStatus: () => invoke('bridge:hostStatus'),
  metricsBadge: () => invoke('metrics:badge'),
  pluginsInstalled: () => invoke('plugins:installed'),
  pluginsReview: (raw: string, opts?: { deep?: boolean; model2?: string; model3?: string }) => invoke('plugins:review', raw, opts),
  pluginsApply: (raw: string, opts?: { force?: boolean }) => invoke('plugins:apply', raw, opts),
  pluginsCancel: () => invoke('plugins:cancel'),
  pluginsUpdate: (slug: string, opts?: { apply?: boolean }) => invoke('plugins:update', slug, opts),
  pluginsRemove: (slug: string) => invoke('plugins:remove', slug),
  evalProjectTasks: (opts?: { limit?: number; dryRun?: boolean; model?: string }) => invoke('eval:projectTasks', opts),
  abRun: (opts: { variantB?: string; mode?: 'quick' | 'all' | 'prompt'; prompt?: string; repeat?: number; variantA?: string; axis?: 'repoMap' | 'autoVerify' | 'budget' | 'memory' }) => invoke('ab:run', opts),
  evalShareCard: () => invoke('eval:shareCard'),
  evalTasks: () => invoke('eval:tasks'),
  evalModels: (opts?: { models?: string[]; quick?: boolean; tasks?: string[] }) => invoke('eval:models', opts),
  getRules: () => invoke('rules:get'),
  saveRules: (text: string) => invoke('rules:save', text),
  trustRules: () => invoke('rules:trust'),
  allowRule: (rule: string) => invoke('rules:allow', rule),
  addMemory: (note: string) => invoke('memory:add', note),
  readMemory: () => invoke('memory:read'),
  sessionStats: () => invoke('sessions:stats'),
  exportSession: (format?: 'md' | 'json') => invoke('sessions:export', format),
  sandboxStatus: () => invoke('sandbox:status'),
  sandboxSet: (patch: Record<string, unknown>) => invoke('sandbox:set', patch),
  lspStatus: () => invoke('lsp:status'),
  lspToggle: (name: string) => invoke('lsp:toggle', name),
  lspTrust: () => invoke('lsp:trust'),
  bridgeStatus: () => invoke('bridge:status'),
  bridgeStart: (opts?: { port?: number }) => invoke('bridge:start', opts),
  bridgeStop: () => invoke('bridge:stop'),
  bridgeRotate: () => invoke('bridge:rotate'),
  securityScan: (opts?: { deps?: boolean; only?: string[] }) => invoke('security:scan', opts),
  listPlugins: () => invoke('plugins:list'),
  scaffoldPlugin: (name: string) => invoke('plugins:scaffold', name),
  trustPlugin: (slug: string) => invoke('plugins:trust', slug),
  togglePlugin: (slug: string) => invoke('plugins:toggle', slug),
  listAgents: () => invoke('agents:list'),
  startAgents: (tasks: { label: string; task: string }[]) => invoke('agents:start', tasks),
  stopAgent: (id: string) => invoke('agents:stop', id),
  mergeAgent: (id: string, squash?: boolean) => invoke('agents:merge', id, squash),
  discardAgent: (id: string) => invoke('agents:discard', id),
  agentDiff: (id: string) => invoke('agents:diff', id),
  clearAgents: () => invoke('agents:clear'),
  listProcesses: () => invoke('processes:list'),
  stopProcess: (id: string) => invoke('processes:stop', id),
  listSkills: () => invoke('skills:list'),
  scaffoldSkill: (name: string) => invoke('skills:scaffold', name),
  skillBody: (name: string) => invoke('skills:body', name),
  onEvent: (cb: (e: unknown) => void) => {
    const handler = (_: unknown, e: unknown) => cb(e);
    ipcRenderer.on('agent:event', handler);
    return () => ipcRenderer.removeListener('agent:event', handler);
  },
});
